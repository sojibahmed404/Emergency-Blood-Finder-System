-- Schema for the Emergency Blood Finder System on PostgreSQL/Supabase.
-- Safe to run on a new project; it does not delete or overwrite existing data.

CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'RECEIVER'
    CHECK (role IN ('DONOR', 'RECEIVER', 'ADMIN')),
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
    CHECK (status IN ('ACTIVE', 'BLOCKED')),
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.donors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE
    REFERENCES public.users(id) ON DELETE CASCADE,
  blood_group VARCHAR(10) NOT NULL
    CHECK (blood_group IN ('A_POS', 'A_NEG', 'B_POS', 'B_NEG',
                           'AB_POS', 'AB_NEG', 'O_POS', 'O_NEG')),
  location VARCHAR(255),
  phone VARCHAR(20),
  availability BOOLEAN NOT NULL DEFAULT TRUE,
  last_donated DATE
);

CREATE TABLE IF NOT EXISTS public.blood_banks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  location VARCHAR(255) NOT NULL,
  contact VARCHAR(50) NOT NULL,
  description VARCHAR(500),
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_id BIGINT NOT NULL
    REFERENCES public.users(id) ON DELETE CASCADE,
  donor_id BIGINT NOT NULL
    REFERENCES public.donors(id) ON DELETE CASCADE,
  message TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.donors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.blood_banks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.requests ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.users, public.donors, public.blood_banks, public.requests
  FROM anon, authenticated;
GRANT ALL ON public.users, public.donors, public.blood_banks, public.requests
  TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
